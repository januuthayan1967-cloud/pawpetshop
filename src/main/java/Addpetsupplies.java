    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
        String name = txtName.getText().trim();
        String priceStr = txtPrice.getText().trim();
        String qtyStr = txtQuantity.getText().trim();
        String threshStr = txtThreshold.getText().trim();
        String description = txtDescription.getText().trim();
        String categoryName = (String) comboCategory.getSelectedItem();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the product name.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtName.requestFocusInWindow();
            return;
        }

        BigDecimal price;
        try {
            price = new BigDecimal(priceStr);
            if (price.compareTo(BigDecimal.ZERO) < 0) {
                throw new NumberFormatException();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid positive price (e.g. 19.99).", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtPrice.requestFocusInWindow();
            return;
        }

        int quantity;
        try {
            quantity = Integer.parseInt(qtyStr);
            if (quantity < 0) {
                throw new NumberFormatException();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid integer for quantity (e.g. 20).", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtQuantity.requestFocusInWindow();
            return;
        }

        int threshold = 5;
        try {
            if (!threshStr.isEmpty()) {
                threshold = Integer.parseInt(threshStr);
            }
        } catch (Exception e) {
            threshold = 5;
        }

        try {
            int categoryId = 1;
            List<Category> allCats = categoryService.getAllCategories();
            for (Category c : allCats) {
                if (c.getName().equalsIgnoreCase(categoryName)) {
                    categoryId = c.getId();
                    break;
                }
            }

            Product p = new Product();
            p.setName(name);
            p.setCategoryId(categoryId);
            p.setCategoryName(categoryName);
            p.setPrice(price);
            p.setQuantity(quantity);
            p.setLowStockThreshold(threshold);
            p.setDescription(description);
            p.setStatus("ACTIVE");

            productService.addProduct(p);

            JOptionPane.showMessageDialog(this,
                "✓ Pet supply '" + name + "' added successfully!\nCategory: " + categoryName + "\nPrice: $" + price + " | Stock: " + quantity,
                "Success",
                JOptionPane.INFORMATION_MESSAGE);

            btnClearFormActionPerformed(evt);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                "Error adding product: " + ex.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddProductActionPerformed

