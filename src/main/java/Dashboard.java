    /**
     * Load catalog data into cashier table.
     */
    public void loadCatalogData() {
        try {
            List<Product> products = productService.getAllProducts(true);
            DefaultTableModel model = (DefaultTableModel) tblCatalog.getModel();
            model.setRowCount(0);

            int lowStockCount = 0;
            for (Product p : products) {
                if (p.getQuantity() <= p.getLowStockThreshold()) {
                    lowStockCount++;
                }
                model.addRow(new Object[]{
                    p.getId(),
                    p.getName(),
                    p.getCategoryName() != null ? p.getCategoryName() : "General",
                    String.format("$%.2f", p.getPrice().doubleValue()),
                    p.getQuantity() + " units"
                });
            }

            lblStatTotalProducts.setText(products.size() + " Items");
            lblStatLowStock.setText(lowStockCount + " Items Low");
        } catch (Exception ex) {
            System.err.println("[Dashboard] Error loading catalog: " + ex.getMessage());
        }
    }

