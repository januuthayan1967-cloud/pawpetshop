    private void loadCategories() {
        try {
            categoryList = categoryService.getAllCategories();
            comboCategory.removeAllItems();
            for (Category c : categoryList) {
                comboCategory.addItem(c.getName());
            }
        } catch (Exception ex) {
            System.err.println("[Updatepetsupplies] Error loading categories: " + ex.getMessage());
        }
    }

    private void loadProducts() {
        try {
            isPopulating = true;
            productList = productService.getAllProducts(false);
            comboSelectProduct.removeAllItems();
            for (Product p : productList) {
                comboSelectProduct.addItem("#" + p.getId() + " - " + p.getName() + " (" + (p.getCategoryName() != null ? p.getCategoryName() : "General") + ")");
            }
            isPopulating = false;

            if (!productList.isEmpty()) {
                comboSelectProduct.setSelectedIndex(0);
                populateFieldsWithProduct(productList.get(0));
            }
        } catch (Exception ex) {
            isPopulating = false;
            System.err.println("[Updatepetsupplies] Error loading products: " + ex.getMessage());
        }
    }

    private void populateFieldsWithProduct(Product p) {
        txtName.setText(p.getName());
        txtPrice.setText(p.getPrice().toPlainString());
        txtQuantity.setText(String.valueOf(p.getQuantity()));
        txtThreshold.setText(String.valueOf(p.getLowStockThreshold()));

        if (p.getStatus() != null && "INACTIVE".equalsIgnoreCase(p.getStatus())) {
            comboStatus.setSelectedItem("INACTIVE");
        } else {
            comboStatus.setSelectedItem("ACTIVE");
        }

        if (p.getCategoryName() != null) {
            comboCategory.setSelectedItem(p.getCategoryName());
        }
    }

