    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int index = comboSelectProduct.getSelectedIndex();
        if (index < 0 || index >= productList.size()) {
            JOptionPane.showMessageDialog(this, "Please select a product to update.", "Select Product", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Product selected = productList.get(index);
        String name = txtName.getText().trim();
        String priceStr = txtPrice.getText().trim();
        String qtyStr = txtQuantity.getText().trim();
        String threshStr = txtThreshold.getText().trim();
        String status = (String) comboStatus.getSelectedItem();
        String categoryName = (String) comboCategory.getSelectedItem();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Product name cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            BigDecimal price = new BigDecimal(priceStr);
            int qty = Integer.parseInt(qtyStr);
            int threshold = Integer.parseInt(threshStr);

            int categoryId = selected.getCategoryId();
            for (Category c : categoryList) {
                if (c.getName().equalsIgnoreCase(categoryName)) {
                    categoryId = c.getId();
                    break;
                }
            }

            selected.setName(name);
            selected.setCategoryId(categoryId);
            selected.setCategoryName(categoryName);
            selected.setPrice(price);
            selected.setQuantity(qty);
            selected.setLowStockThreshold(threshold);
            selected.setStatus(status);

            productService.updateProduct(selected);

            JOptionPane.showMessageDialog(this, "✓ Product '" + name + "' updated successfully in database!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadProducts();
        } catch (ProductService.ValidationException ve) {
            JOptionPane.showMessageDialog(this, ve.getMessage(), "Validation Error", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error updating product: " + ex.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeactivateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeactivateActionPerformed
        int index = comboSelectProduct.getSelectedIndex();
        if (index < 0 || index >= productList.size()) return;

        Product selected = productList.get(index);
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to deactivate/delete product '" + selected.getName() + "'?",
            "Confirm Deactivation",
            JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                productService.deleteOrDeactivateProduct(selected.getId());
                JOptionPane.showMessageDialog(this, "Product deactivated/removed.", "Updated", JOptionPane.INFORMATION_MESSAGE);
                loadProducts();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeactivateActionPerformed

