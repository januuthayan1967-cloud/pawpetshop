    private void chkShowPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkShowPasswordActionPerformed
        if (chkShowPassword.isSelected()) {
            txtPassword.setEchoChar((char) 0);
            txtConfirmPassword.setEchoChar((char) 0);
        } else {
            txtPassword.setEchoChar('•');
            txtConfirmPassword.setEchoChar('•');
        }
    }//GEN-LAST:event_chkShowPasswordActionPerformed

    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
        String fullName = txtFullName.getText().trim();
        String username = txtUsername.getText().trim();
        String email = txtEmail.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();
        String confirmPassword = new String(txtConfirmPassword.getPassword()).trim();

        try {
            User created = userService.createCashier(fullName, username, email, password, confirmPassword);
            JOptionPane.showMessageDialog(this,
                "✓ Cashier account created successfully!\n\n" +
                "• Full Name: " + created.getFullName() + "\n" +
                "• Username: " + created.getUsername() + "\n" +
                "• Email: " + created.getEmail() + "\n" +
                "• Security: BCrypt Hashed & Salted (12 rounds)\n\n" +
                "The cashier can now log in to the PawMart Cashier Station.",
                "Account Created",
                JOptionPane.INFORMATION_MESSAGE);

            btnClearFormActionPerformed(evt);
        } catch (UserService.ValidationException ve) {
            lblStatusMessage.setText("⚠ " + ve.getMessage());
            lblStatusMessage.setForeground(new java.awt.Color(242, 100, 25));
            JOptionPane.showMessageDialog(this, ve.getMessage(), "Validation Error", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            lblStatusMessage.setText("Error: " + ex.getMessage());
            lblStatusMessage.setForeground(new java.awt.Color(220, 38, 38));
            JOptionPane.showMessageDialog(this, "Failed to create cashier: " + ex.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCreateAccountActionPerformed

