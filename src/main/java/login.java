    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String usernameInput = txtUsername.getText().trim();
        String passwordInput = new String(txtPassword.getPassword()).trim();
        String selectedRoleStr = (String) comboRole.getSelectedItem();

        if (usernameInput.isEmpty() || passwordInput.isEmpty()) {
            lblStatusMessage.setText("Please enter both username and password.");
            JOptionPane.showMessageDialog(this, "Please enter both username and password.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Role expectedRole = "Manager".equalsIgnoreCase(selectedRoleStr) ? Role.MANAGER : Role.CASHIER;

        try {
            User loggedUser = AuthService.getInstance().login(usernameInput, passwordInput);
            if (loggedUser != null) {
                if (loggedUser.getRole() != expectedRole) {
                    lblStatusMessage.setText("Role mismatch: account is a " + loggedUser.getRole());
                    JOptionPane.showMessageDialog(this,
                        "Account '" + usernameInput + "' is registered as " + loggedUser.getRole() +
                        ", not " + selectedRoleStr + ". Please switch the role dropdown.",
                        "Role Mismatch",
                        JOptionPane.WARNING_MESSAGE);
                    return;
                }

                lblStatusMessage.setText("Login successful! Loading dashboard...");
                this.dispose();

                if (loggedUser.getRole() == Role.MANAGER) {
                    Managerpage managerPage = new Managerpage();
                    managerPage.setVisible(true);
                } else {
                    Dashboard cashierDashboard = new Dashboard();
                    cashierDashboard.setVisible(true);
                }
            }
        } catch (AuthService.AuthenticationException ex) {
            lblStatusMessage.setText(ex.getMessage());
            JOptionPane.showMessageDialog(this,
                ex.getMessage() + "\n\n" +
                "Default Credentials:\n" +
                "• Manager: admin / admin123\n" +
                "• Cashier: cashier / cashier123",
                "Authentication Failed",
                JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            lblStatusMessage.setText("Database error: " + ex.getMessage());
            JOptionPane.showMessageDialog(this,
                "Error connecting to PawMart database: " + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

